"""
Temporal approval workflow.

Flow:
  1. Agent detects NEEDS_APPROVAL chunks
  2. Starts this workflow with the request details
  3. Workflow writes pending_approval tuples to OpenFGA (done by agent/nodes.py
     before starting, so the tuple exists even if the workflow hasn't started yet)
  4. Notifies the approver (Slack/email) with HMAC-signed approve/deny deep-link
  5. Waits up to 24h for an `approval_decision` signal
  6. On approve: writes viewer tuples, revokes pending tuples, notifies user,
     optionally sends A2A callback
  7. On deny/timeout: revokes pending tuples, notifies user / originating agent

Security fixes:
  H-6  — pending_approval OpenFGA tuples are revoked on BOTH denial AND timeout
          (previously only removed on approval), preventing stale pending state
          that would block future requests.
  H-7  — originating_delegated_token removed from ApprovalInput; the callback
          activity now uses the agent's own client-credentials token instead of
          a stored user-delegated token, keeping user tokens out of Temporal's
          persistent event history.
  L-1  — structlog replaced with workflow.logger inside workflow code so log
          entries are correctly associated with workflow execution context.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from datetime import timedelta
from typing import Optional

from temporalio import workflow
from temporalio.common import RetryPolicy
from temporalio.exceptions import TimeoutError as TemporalTimeoutError

with workflow.unsafe.imports_passed_through():
    from workflow.activities import (
        A2ACallbackInput,
        GrantAccessInput,
        NotifyApproverInput,
        NotifyUserInput,
        RevokeApprovalInput,
        grant_access_in_openfga,
        notify_approver,
        notify_user_of_decision,
        revoke_pending_in_openfga,
        send_a2a_callback,
    )
    from config import settings

NO_RETRY = RetryPolicy(maximum_attempts=1)
RETRY_3 = RetryPolicy(maximum_attempts=3, initial_interval=timedelta(seconds=5))


@dataclass
class ApprovalInput:
    approval_request_id: str
    user_id: str
    chunk_ids: list[str]
    query: str

    # Approver details (resolved from OpenFGA `owner` relation before starting)
    approver_id: str
    approver_slack_id: str | None = None
    approver_email: str | None = None

    # For cross-cluster flows: originating A2A task and agent URL.
    # H-7 FIX: originating_delegated_token is intentionally NOT stored here.
    # The send_a2a_callback activity obtains a fresh token via client credentials.
    originating_task_id: str | None = None
    originating_agent_url: str | None = None

    # Q-7 FIX: snapshot approval_timeout_seconds at workflow-start time so
    # Temporal replay is deterministic even if the env var changes mid-flight.
    # The caller (nodes.py) is responsible for populating this from settings.
    timeout_seconds: int = 86400   # default 24 h; overridden by nodes.py


@dataclass
class ApprovalDecisionSignal:
    decision: str          # "approved" | "denied"
    reason: str = ""
    approver_id: str = ""


@dataclass
class ApprovalResult:
    decision: str          # "approved" | "denied" | "timeout"
    reason: str = ""


@workflow.defn
class ApprovalWorkflow:

    def __init__(self) -> None:
        self._decision: ApprovalDecisionSignal | None = None

    @workflow.signal
    async def approval_decision(self, signal: ApprovalDecisionSignal) -> None:
        """Receives the approve/deny signal from the approval UI."""
        self._decision = signal
        workflow.logger.info(
            "approval_signal_received",
            decision=signal.decision,
            approver=signal.approver_id,
        )

    @workflow.run
    async def run(self, inp: ApprovalInput) -> ApprovalResult:
        workflow.logger.info(
            "approval_workflow_started",
            request_id=inp.approval_request_id,
            user=inp.user_id,
        )

        # Notify the approver with HMAC-signed deep-link (generated by activity)
        await workflow.execute_activity(
            notify_approver,
            NotifyApproverInput(
                approval_request_id=inp.approval_request_id,
                user_id=inp.user_id,
                chunk_ids=inp.chunk_ids,
                query=inp.query,
                approver_id=inp.approver_id,
                approver_slack_id=inp.approver_slack_id,
                approver_email=inp.approver_email,
            ),
            start_to_close_timeout=timedelta(seconds=30),
            retry_policy=RETRY_3,
        )

        # Q-7 FIX: use inp.timeout_seconds (snapshotted at start) instead of
        # reading settings.approval_timeout_seconds here.  Temporal replays this
        # workflow function deterministically — reading live config inside
        # @workflow.run is non-deterministic if the value changes between runs.
        try:
            await workflow.wait_condition(
                lambda: self._decision is not None,
                timeout=timedelta(seconds=inp.timeout_seconds),
            )
        except TemporalTimeoutError:
            await self._handle_timeout(inp)
            return ApprovalResult(
                decision="timeout",
                reason="No response from approver within timeout",
            )

        decision = self._decision  # type: ignore[assignment]

        if decision.decision == "approved":
            return await self._handle_approved(inp, decision)
        else:
            return await self._handle_denied(inp, decision)

    async def _handle_approved(
        self, inp: ApprovalInput, decision: ApprovalDecisionSignal
    ) -> ApprovalResult:
        # Grant viewer access and revoke pending tuple atomically
        await workflow.execute_activity(
            grant_access_in_openfga,
            GrantAccessInput(user_id=inp.user_id, chunk_ids=inp.chunk_ids),
            start_to_close_timeout=timedelta(seconds=30),
            retry_policy=RETRY_3,
        )
        # grant_access_in_openfga already revokes pending tuples (see activities.py)

        # Notify the user
        await workflow.execute_activity(
            notify_user_of_decision,
            NotifyUserInput(
                user_id=inp.user_id,
                message="Your access request has been approved. You can now query the requested data.",
                callback_task_id=inp.originating_task_id,
            ),
            start_to_close_timeout=timedelta(seconds=30),
            retry_policy=NO_RETRY,
        )

        # Cross-cluster callback (H-7: no stored token — activity uses client creds)
        if inp.originating_agent_url and inp.originating_task_id:
            await workflow.execute_activity(
                send_a2a_callback,
                A2ACallbackInput(
                    peer_agent_url=inp.originating_agent_url,
                    task_id=inp.originating_task_id,
                    decision="approved",
                    message="Access approved. Re-send the original request to retrieve data.",
                ),
                start_to_close_timeout=timedelta(seconds=30),
                retry_policy=RETRY_3,
            )

        workflow.logger.info("approval_workflow_approved", request_id=inp.approval_request_id)
        return ApprovalResult(decision="approved", reason=decision.reason)

    async def _handle_denied(
        self, inp: ApprovalInput, decision: ApprovalDecisionSignal
    ) -> ApprovalResult:
        # H-6 FIX: revoke pending tuples on denial so user can request again later
        await workflow.execute_activity(
            revoke_pending_in_openfga,
            RevokeApprovalInput(user_id=inp.user_id, chunk_ids=inp.chunk_ids),
            start_to_close_timeout=timedelta(seconds=30),
            retry_policy=RETRY_3,
        )

        await workflow.execute_activity(
            notify_user_of_decision,
            NotifyUserInput(
                user_id=inp.user_id,
                message=f"Your access request was denied. Reason: {decision.reason or 'Not specified'}",
                callback_task_id=inp.originating_task_id,
            ),
            start_to_close_timeout=timedelta(seconds=30),
            retry_policy=NO_RETRY,
        )

        if inp.originating_agent_url and inp.originating_task_id:
            await workflow.execute_activity(
                send_a2a_callback,
                A2ACallbackInput(
                    peer_agent_url=inp.originating_agent_url,
                    task_id=inp.originating_task_id,
                    decision="denied",
                    message=f"Access denied. Reason: {decision.reason or 'Not specified'}",
                ),
                start_to_close_timeout=timedelta(seconds=30),
                retry_policy=RETRY_3,
            )

        return ApprovalResult(decision="denied", reason=decision.reason)

    async def _handle_timeout(self, inp: ApprovalInput) -> None:
        # H-6 FIX: revoke pending tuples on timeout (same as denial)
        await workflow.execute_activity(
            revoke_pending_in_openfga,
            RevokeApprovalInput(user_id=inp.user_id, chunk_ids=inp.chunk_ids),
            start_to_close_timeout=timedelta(seconds=30),
            retry_policy=RETRY_3,
        )

        await workflow.execute_activity(
            notify_user_of_decision,
            NotifyUserInput(
                user_id=inp.user_id,
                message="Your access request timed out with no response from the approver.",
                callback_task_id=inp.originating_task_id,
            ),
            start_to_close_timeout=timedelta(seconds=30),
            retry_policy=NO_RETRY,
        )

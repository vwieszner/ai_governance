"""
FastAPI application — exposes:
  GET  /.well-known/agent-card.json   A2A AgentCard
  POST /tasks/send                    A2A task submission (SSE streaming)
  GET  /tasks/{task_id}               A2A task status poll
  POST /tasks/{task_id}/callback      A2A push notification webhook (cross-cluster)
  GET  /approve/{request_id}          Approval UI endpoint (HMAC-signed deep-link)
  GET  /health                        Kubernetes liveness probe

Security fixes applied:
  C-2  — /approve endpoint verifies an HMAC-SHA256-signed token so only
          Slack / email deep-links generated by the workflow can trigger it.
          No unauthenticated stranger can approve/deny by guessing a UUID.
  C-3  — Task store backed by Redis (redis.asyncio) with configurable TTL.
          Replaces the in-memory dict that was wiped on restart and couldn't
          be shared across multiple replicas.
  C-4  — /tasks/{id}/callback verifies the caller's JWT client_id is one of
          the configured peer agent client IDs (settings.peer_agent_client_ids_list).
  M-3  — Request bodies are rejected with 413 if they exceed
          settings.max_request_body_bytes (default 1 MB).
"""
